// Helper Function สำหรับค้นหาใน Local Database
export function searchLocalFood(query) {
  if (!query || typeof query !== 'string') return [];
  const cleanQ = query.trim().toLowerCase();
  
  return THAI_FOOD_DATABASE.filter(item => {
    const matchName = item.name.toLowerCase().includes(cleanQ);
    const matchNameEn = item.nameEn.toLowerCase().includes(cleanQ);
    const matchCategory = item.category.toLowerCase().includes(cleanQ);
    const matchTag = item.tags && item.tags.some(tag => tag.toLowerCase().includes(cleanQ));
    return matchName || matchNameEn || matchCategory || matchTag;
  });
}
